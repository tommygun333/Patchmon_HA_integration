from .api import PatchMonError
from .coordinator import PatchMonCoordinator
from .entity import PatchMonHostEntity
from .const import DOMAIN
from .patch_utils import run_progress


_LOGGER = logging.getLogger(__name__)


def _slug(value: str) -> str:
    """Create stable, ASCII-only HA entity-id fragments."""
    ascii_text = unicodedata.normalize("NFKD", value).encode("ascii", "ignore").decode().lower()
    return re.sub(r"_+", "_", re.sub(r"[^a-z0-9]+", "_", ascii_text)).strip("_") or "unknown"


async def async_setup_entry(
    hass: HomeAssistant,
    entry: ConfigEntry,
    async_add_entities: AddEntitiesCallback,
) -> None:
    """Create only explicitly tracked entities, including newly discovered hosts."""
    coordinator: PatchMonCoordinator = entry.runtime_data
    # Configuration changes unload/reload the platform, but HA retains the
    # registry entries unless the integration explicitly removes old ones.
    # Only prune entities generated by this integration's package watchlist;
    # never touch its other entities or another integration's update entities.
    expected_ids = {
        f"{entry.entry_id}_{host_id}_pkg_{name}"
        for host_id, names in coordinator.tracked_packages.items()
        for name in names
    }
    registry = er.async_get(hass)
    for registered in er.async_entries_for_config_entry(registry, entry.entry_id):
        if (
            registered.domain == "update"
            and registered.platform == DOMAIN
            and registered.unique_id.startswith(f"{entry.entry_id}_")
            and "_pkg_" in registered.unique_id
            and registered.unique_id not in expected_ids
        ):
            registry.async_remove(registered.entity_id)
            continue
        # Existing registry entities retain their unique_id (and therefore
        # history). Rename their entity_id in-place instead of deleting and
        # recreating them, which would lose customizations.
        if (
            registered.domain == "update"
            and registered.platform == DOMAIN
            and registered.unique_id in expected_ids
            and not registered.entity_id.startswith("update.patchmon_")
        ):
            new_id = "update.patchmon_" + registered.entity_id.removeprefix("update.")
            # Do not rename unrelated entities or replace a conflicting ID.
            if registry.async_get(new_id) is not None:
                _LOGGER.warning(
                    "Cannot rename PatchMon update %s to %s: ID already exists",
                    registered.entity_id, new_id,
                )
                continue
            try:
                registry.async_update_entity(registered.entity_id, new_entity_id=new_id)
            except ValueError as err:
                _LOGGER.warning("Cannot rename PatchMon update %s: %s", registered.entity_id, err)

    known: set[tuple[str, str]] = set()

    @callback
    def add_watched() -> None:
        new: list[PatchMonPackageUpdate] = []
        for host_id in (coordinator.data or {}):
            for name in coordinator.watched_packages(host_id):
                key = (host_id, name)
                if key not in known:
                    known.add(key)
                    new.append(PatchMonPackageUpdate(coordinator, host_id, name))
        if new:
            async_add_entities(new)

    add_watched()
    entry.async_on_unload(coordinator.async_add_listener(add_watched))


class PatchMonPackageUpdate(PatchMonHostEntity, UpdateEntity):
    """Represents a specific package on one specific PatchMon host."""

    _attr_icon = "mdi:package-up"

    def __init__(self, coordinator: PatchMonCoordinator, host_id: str, name: str) -> None:
        super().__init__(coordinator, host_id)
        self.package_name = name
        self._attr_name = name
        self._attr_title = name
        self._attr_unique_id = f"{coordinator.entry.entry_id}_{host_id}_pkg_{name}"
        self._attr_supported_features = UpdateEntityFeature.PROGRESS
        if coordinator.client.patching_enabled:
            self._attr_supported_features |= UpdateEntityFeature.INSTALL

    @property
    def suggested_object_id(self) -> str:
        """Force update.patchmon_* for newly registered watched packages."""
        host = self.host
        hostname = str(host.get("friendly_name") or host.get("hostname") or self.host_id)
        return f"patchmon_{_slug(hostname)}_{_slug(self.package_name)}"

    @property
    def available(self) -> bool:
        return (
            super().available
            and self.host.get("_packages_loaded") is True
            and self.coordinator.tracked_package(self.host_id, self.package_name) is not None
        )

    @property
    def installed_version(self) -> str | None:
        package = self.coordinator.tracked_package(self.host_id, self.package_name)
        value = package.get("current_version") if package else None
        return str(value) if value else None

    @property
    def latest_version(self) -> str | None:
        package = self.coordinator.tracked_package(self.host_id, self.package_name)
        if not package:
            return None
        if not package.get("needs_update"):
            return self.installed_version
        value = package.get("available_version")
        return str(value) if value else None

    @property
    def in_progress(self) -> bool:
        return self._progress()[0]

    @property
    def update_percentage(self) -> int | None:
        """Stage milestone, NOT a measured installation completion percentage."""
        return self._progress()[1]

    def _progress(self) -> tuple[bool, int | None, str | None]:
        if self.host.get("_patch_run_loaded") is not True:
            return False, None, None
        return run_progress(self.host.get("_patch_run"), self.package_name)

    def version_is_newer(self, latest_version: str, installed_version: str) -> bool:
        """Package manager versions may not be comparable as SemVer.

        Trust PatchMon's needs_update result instead of lexical comparison.
        """
        package = self.coordinator.tracked_package(self.host_id, self.package_name)
        return bool(package and package.get("needs_update"))

    @property
    def extra_state_attributes(self) -> dict[str, Any] | None:
        package = self.coordinator.tracked_package(self.host_id, self.package_name)
        if not package:
            return None
        _, milestone, stage = self._progress()
        return {
            "patch_stage": stage,
            "progress_type": "stage_based",
            "stage_milestone": milestone,
            "security_update": bool(package.get("is_security_update")),
            "needs_update": bool(package.get("needs_update")),
            "package_name": self.package_name,
            "host_id": self.host_id,
            "last_patch_status": (
                self.host.get("_patch_run") or {}
            ).get("status"),
            "last_patch_run_id": (
                self.host.get("_patch_run") or {}
            ).get("id"),
        }

    async def async_install(self, version: str | None, backup: bool, **kwargs) -> None:
        """Queue a package-specific patch; PatchMon performs the actual install."""
        if not self.coordinator.client.patching_enabled:
            raise HomeAssistantError("Configure PatchMon patch credentials before installing")
        if not self.available:
            raise HomeAssistantError("Package inventory is unavailable; refusing a blind update")
        if self.in_progress:
            raise HomeAssistantError("A PatchMon patch run for this package is already in progress")
        if version and version != self.latest_version:
            raise HomeAssistantError("PatchMon can only install the currently available version")
        if backup:
            raise HomeAssistantError("PatchMon does not offer pre-install backups through this API")
        if not self.coordinator.tracked_package(self.host_id, self.package_name).get("needs_update"):
            raise HomeAssistantError("Package is already current")
        try:
            result = await self.coordinator.client.async_patch_host(
                self.host_id, package_names=[self.package_name]
            )
        except PatchMonError as err:
            raise HomeAssistantError(f"Could not queue PatchMon package update: {err}") from err
        # The POST only queued a job. The follow-up task waits for the actual
        # patch run and refreshed host inventory before updating HA versions.
        self.coordinator.follow_patch(self.host_id, [self.package_name], result)
